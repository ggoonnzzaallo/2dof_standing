"""Generate shadow firmware constants from the recorded provisional mounting fit."""
from pathlib import Path
import hashlib
import json

ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'firmware/imu_bench/measurements/2026-11-01/mount_rotation_provisional.json'
r=json.loads(source.read_text())
for capture in r['captures']+[r['independent_inverted_check']]:
    assert hashlib.sha256((ROOT/capture['file']).read_bytes()).hexdigest()==capture['sha256']
assert r['independent_inverted_check']['status']=='passed'
rows=',\n'.join('  {'+','.join(f'{float(x):.9e}f' for x in row)+'}' for row in r['R_sensor_to_base'])
bias=','.join(f'{float(x):.9e}f' for x in r['gyro_bias_candidate_sensor_rad_s'])
text='''#pragma once
// Generated by scripts/generate_imu_mount.py; provisional static calibration.
// Source SHA256: '''+hashlib.sha256(source.read_bytes()).hexdigest()+'''
static const float IMU_ROTATION[3][3]={
'''+rows+'''
};
static const float IMU_GYRO_BIAS[3]={'''+bias+'''};
static inline void imuToBase(const float sensor[3],float base[3]){
  for(int i=0;i<3;++i){base[i]=0;for(int j=0;j<3;++j)base[i]+=IMU_ROTATION[i][j]*sensor[j];}
}
static inline void gyroToBase(const float sensor[3],float base[3]){
  float corrected[3];for(int i=0;i<3;++i)corrected[i]=sensor[i]-IMU_GYRO_BIAS[i];
  imuToBase(corrected,base);
}
'''
out=ROOT/'firmware/policy_shadow/MountCalibration.h'
out.write_text(text)
print(out.relative_to(ROOT))
