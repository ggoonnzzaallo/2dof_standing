"""Build the final-CAD exploratory MJCF with explicit component mass aggregation."""
from pathlib import Path
import hashlib
import json
import xml.etree.ElementTree as ET
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
COLORS = {'base': '.21 .53 .78 1', 'middle': '.91 .57 .20 1', 'upper': '.61 .39 .79 1'}


def numbers(values):
    return ' '.join(f'{float(x):.12g}' for x in values)


def box_inertia(mass, dimensions):
    x, y, z = dimensions
    return np.diag([y*y+z*z, x*x+z*z, x*x+y*y]) * mass / 12


def aggregate(parts):
    mass = sum(p['mass_kg'] for p in parts)
    center = sum(p['mass_kg'] * np.array(p['com_cad_m']) for p in parts) / mass
    tensor = np.zeros((3, 3))
    for part in parts:
        r = np.array(part['com_cad_m']) - center
        tensor += np.array(part['inertia_com_cad_kg_m2']) + part['mass_kg'] * (r @ r * np.eye(3) - np.outer(r, r))
    assert np.linalg.eigvalsh(tensor)[0] > 0
    return {'mass_kg': mass, 'com_cad_m': center.tolist(), 'inertia_com_cad_kg_m2': tensor.tolist()}


def main():
    manifest = json.loads((HERE / 'manifest.json').read_text())
    settings = json.loads((HERE / 'assumptions.json').read_text())
    printed = json.loads((ROOT / 'sim/mass_properties/assigned_properties.json').read_text())
    cad = json.loads((ROOT / 'sim/mass_properties/cad_geometric_properties.json').read_text())
    joint_map = json.loads((ROOT / 'cad/onshape_import/joint_map.json').read_text())
    geometry = json.loads((ROOT / 'cad/onshape_import/geometry.json').read_text())
    joints = joint_map['joints']
    origins = {'base': [0, 0, 0], 'middle': joints[0]['origin_cad_mm'], 'upper': joints[1]['origin_cad_mm']}
    for joint, candidate in zip(joints, geometry['candidate_joints'][:2]):
        assert np.allclose(joint['origin_cad_mm'], candidate['origin_mm']), 'Review structural joint map after CAD change.'
        assert np.allclose(joint['axis_cad'], candidate['axis'])
    assert manifest['step_sha256'] == printed['step_sha256'] == cad['source_sha256']
    assert len(manifest['parts']) == 9, 'Asset generation incomplete.'
    assert 'controller_board' in manifest['parts']
    geom_by_alias = {p['alias']: p for p in cad['parts']}
    parts = [{
        'alias': p['alias'], 'group': p['rigid_group'], 'mass_kg': p['mass_kg'],
        'com_cad_m': p['center_of_mass_cad_m'],
        'inertia_com_cad_kg_m2': p['inertia_about_com_in_cad_axes_kg_m2'],
        'source': p['mass_source'], 'distribution': p['distribution_assumption'],
    } for p in printed['parts']]
    for alias, mass_g in settings['hardware_mass_g'].items():
        geom = geom_by_alias[alias]
        mass = mass_g / 1000
        if geom['cad_brep_valid']:
            com = np.array(geom['uniform_solid_centroid_cad_mm']) / 1000
            tensor = np.array(geom['unit_density_inertia_about_centroid_mm5']) * mass / geom['cad_volume_mm3'] * 1e-6
        else:
            box = np.array(manifest['parts'][alias]['bbox_cad_m'])
            com = box.mean(axis=0)
            tensor = box_inertia(mass, box[1] - box[0])
        parts.append({'alias': alias, 'group': geom['rigid_group'], 'mass_kg': mass,
                      'com_cad_m': com.tolist(), 'inertia_com_cad_kg_m2': tensor.tolist(),
                      'source': settings['hardware_mass_status'][alias]})
    for item in settings['small_hardware_allowance']:
        mass = item['mass_g'] / 1000
        parts.append({'alias': item['group'] + '_small_hardware_allowance', 'group': item['group'],
                      'mass_kg': mass, 'com_cad_m': (np.array(item['center_cad_mm'])/1000).tolist(),
                      'inertia_com_cad_kg_m2': box_inertia(mass, np.array(item['box_size_mm'])/1000).tolist(),
                      'source': settings['small_hardware_status']})
    groups = {g: aggregate([p for p in parts if p['group'] == g]) for g in origins}
    report = {'status': 'EXPLORATORY: hardware estimates, uniform distributions, uncalibrated joints/dynamics',
              'step_sha256': printed['step_sha256'], 'slicer_sha256': printed['slicer_sha256'],
              'assumptions_sha256': hashlib.sha256((HERE/'assumptions.json').read_bytes()).hexdigest(),
              'component_masses': parts, 'groups': groups, 'whole_upright': aggregate(parts),
              'body_frame_origins_cad_mm': origins,
              'wiring_mass': settings['wiring_mass']}
    (HERE / 'body_properties.json').write_text(json.dumps(report, indent=2) + '\n')

    model = ET.Element('mujoco', model='self_righting_final_onshape_exploratory')
    model.append(ET.Comment('Generated by sim/onshape/build_model.py. Read assumptions.json before training or physical transfer.'))
    ET.SubElement(model, 'compiler', angle='radian', inertiafromgeom='false', meshdir='onshape/assets')
    ET.SubElement(model, 'option', timestep=str(settings['physics_timestep_s']), integrator='implicitfast', gravity='0 0 -9.81')
    ET.SubElement(model, 'statistic', center='0 0 .075', extent='.18')
    visual = ET.SubElement(model, 'visual')
    ET.SubElement(visual, 'global', offwidth='960', offheight='720')
    default = ET.SubElement(model, 'default')
    ET.SubElement(default, 'joint', damping=str(settings['joint_damping_Nm_s_per_rad']), armature=str(settings['joint_armature_kg_m2']))
    ET.SubElement(default, 'geom', friction=numbers(settings['floor_friction']), condim='3', solref=f"{settings['contact_timeconstant_s']} 1")
    custom = ET.SubElement(model, 'custom')
    ET.SubElement(custom, 'numeric', name='exploratory_uncalibrated_model', data='1')
    assets = ET.SubElement(model, 'asset')
    world = ET.SubElement(model, 'worldbody')
    ET.SubElement(world, 'light', pos='.1 -.3 .5', dir='-.1 .3 -.5', diffuse='.8 .8 .8')
    ET.SubElement(world, 'geom', name='floor', type='plane', size='1 1 .1', rgba='.92 .93 .94 1')
    camera_pos = np.array([.24,-.27,.20])
    view_z = camera_pos - np.array([0,0,.075]); view_z /= np.linalg.norm(view_z)
    view_x = np.cross([0,0,1],view_z); view_x /= np.linalg.norm(view_x)
    view_y = np.cross(view_z,view_x)
    ET.SubElement(world, 'camera', name='overview', pos=numbers(camera_pos), xyaxes=numbers(np.r_[view_x,view_y]), fovy='35')
    bodies = {}
    initial_base_height = .001 - manifest['parts']['base']['bbox_cad_m'][0][2]
    for group, parent in [('base', None), ('middle', 'base'), ('upper', 'middle')]:
        origin = np.array(origins[group]) / 1000
        parent_origin = np.zeros(3) if parent is None else np.array(origins[parent]) / 1000
        position = np.array([0, 0, initial_base_height]) if parent is None else origin - parent_origin
        body = ET.SubElement(world if parent is None else bodies[parent], 'body', name=group, pos=numbers(position))
        bodies[group] = body
        if parent is None:
            ET.SubElement(body, 'freejoint', name='floating_base')
        else:
            limit = np.deg2rad(settings['joint_limit_degrees'])
            ET.SubElement(body, 'joint', name='j1' if group == 'middle' else 'j2', type='hinge',
                          axis=numbers(joints[0 if group == 'middle' else 1]['axis_cad']), range=numbers([-limit, limit]))
        properties = groups[group]
        tensor = np.array(properties['inertia_com_cad_kg_m2'])
        ET.SubElement(body, 'inertial', pos=numbers(np.array(properties['com_cad_m']) - origin),
                      mass=str(properties['mass_kg']), fullinertia=numbers(tensor[([0,1,2,0,0,1],[0,1,2,1,2,2])]))
    for alias, part in manifest['parts'].items():
        group = part['group']
        body = bodies[group]
        # Asset coordinates retain CAD placements; translate from CAD to this body frame.
        offset = -np.array(origins[group]) / 1000
        visual_name = alias + '_visual'
        ET.SubElement(assets, 'mesh', name=visual_name, file=part['visual'])
        color = COLORS[group] if alias in {p['alias'] for p in printed['parts']} else (
            '.12 .13 .14 1' if 'servo' in alias else '.55 .58 .62 1' if alias == 'battery' else '.18 .36 .24 1')
        ET.SubElement(body, 'geom', name=visual_name, type='mesh', mesh=visual_name, pos=numbers(offset),
                      group='1', contype='0', conaffinity='0', mass='0', rgba=color)
        for i, filename in enumerate(part['collision_meshes']):
            name = f'{alias}_collision_{i:02d}'
            ET.SubElement(assets, 'mesh', name=name, file=filename)
            ET.SubElement(body, 'geom', name=name, type='mesh', mesh=name, pos=numbers(offset),
                          group='3', mass='0', rgba=COLORS[group])
        if not part['collision_meshes']:
            box = np.array(part['bbox_cad_m'])
            ET.SubElement(body, 'geom', name=alias+'_collision', type='box',
                          pos=numbers(box.mean(axis=0)+offset), size=numbers((box[1]-box[0])/2),
                          group='3', mass='0', rgba=COLORS[group])
    board = next(p for p in parts if p['alias'] == 'controller_board')
    ET.SubElement(bodies['base'], 'site', name='imu', pos=numbers(board['com_cad_m']), size='.001', rgba='1 0 0 1')
    contact = ET.SubElement(model, 'contact')
    ET.SubElement(contact, 'exclude', body1='base', body2='middle')
    ET.SubElement(contact, 'exclude', body1='middle', body2='upper')
    actuator = ET.SubElement(model, 'actuator')
    limit = settings['servo_torque_limit_Nm']
    for joint in ('j1', 'j2'):
        ET.SubElement(actuator, 'motor', name=joint+'_torque', joint=joint, ctrlrange=numbers([-limit, limit]))
    sensor = ET.SubElement(model, 'sensor')
    ET.SubElement(sensor, 'gyro', name='gyro', site='imu')
    ET.SubElement(sensor, 'accelerometer', name='accel', site='imu')
    key = ET.SubElement(model, 'keyframe')
    ET.SubElement(key, 'key', name='upright', qpos=numbers([0,0,initial_base_height,1,0,0,0,0,0]))
    ET.indent(model, space='  ')
    ET.ElementTree(model).write(ROOT / 'sim/robot.xml', encoding='unicode')
    print(f"Generated sim/robot.xml: {report['whole_upright']['mass_kg']*1000:.3f} g with explicit exploratory allowances", flush=True)


if __name__ == '__main__':
    main()
